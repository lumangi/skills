#!/usr/bin/env node
// Emit the reviewable inventory tables from enumerate.mjs + classify.mjs output.
// Usage: node make-inventory.mjs inv.json cls.json > inventory.md
import { readFileSync } from 'node:fs'
const inv = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const cls = JSON.parse(readFileSync(process.argv[3], 'utf8'))
const rel = (f) => f.replace('AcumaticaBase/', '')

const HEADER_GUARD = /response\.headers/
const up = inv.uppercase.sites
const headers = up.filter(s => HEADER_GUARD.test(s.operand))
const others = up.filter(s => !HEADER_GUARD.test(s.operand))

console.log(`# Expression type-guard inventory

Generated by \`enumerate.mjs\` + \`classify.mjs\` (see this directory). Do not hand-edit.

- \`$uppercase\` sites: **${up.length}** after this pass (**153** before it; the 2 checkbox sites lost their \`$uppercase\` call).
  ${headers.length} are content-type header guards, ${others.length} are other.
- JSONata comparison operators: **${cls.length}**

## 1. \`$uppercase\` — the ${others.length} non-header sites

| file:line | operand | source | verdict |
|---|---|---|---|`)
const UP_VERDICT = {
  'components/Customers/customer-billing.jigx:115': ['checkbox value, real Acumatica boolean', '**FIXED** — `$uppercase(true)` throws and blanks the tab'],
  'jigs/Customers/Edit/edit-customer-billing.jigx:133': ['checkbox value, real Acumatica boolean', '**FIXED** — same throw on the edit screen'],
  'components/Customers/address-sub-titles.jigx:30': ['malformed `$uppercase(000)(...)`', 'leave, unreachable — nothing references this jig'],
}
for (const s of others) {
  const key = rel(s.file) + ':' + s.line
  const [src, verdict] = UP_VERDICT[key] || [
    /\$trim\(/.test(s.operand) ? '`$trim()` output' : /jig\.inputs|inputs\./.test(s.operand) ? 'screen input' : /outputs\./.test(s.operand) ? 'dropdown output' : /current\.item/.test(s.operand) ? 'sqlite text column' : '.value path',
    /\$trim\(/.test(s.operand)
      ? 'leave — string from `getWhoAmI`. NOTE: `$trim(null)` itself throws, so a null login/fullName would throw here; not observed on device'
      : 'leave, cannot be non-string',
  ]
  console.log(`| ${key} | \`${s.operand.replace(/\|/g, '\\|')}\` | ${src} | ${verdict} |`)
}

console.log(`
## 2. JSONata comparisons — verdicts

| verdict | count | reason |
|---|---|---|`)
const counts = {}
for (const r of cls) counts[r.verdict] = (counts[r.verdict] || 0) + 1
const REASON = {
  'LEAVE-safe-by-construction': 'both operands are numeric literals or `$count()`/`$sum()` output — always a number',
  'LEAVE-already-type-guarded': 'the same line already applies `$type(x) = \'number\'` (includes the 11 sites fixed in this pass)',
  'LEAVE-commented-out': 'commented-out YAML — cannot evaluate',
  'LEAVE-sql-not-jsonata': 'SQLite inside a `query:` block, not JSONata',
  'REVIEW-number-cast': '`$number(...)` operand — safe only where the argument is never null/`{}`/`""`',
  'REVIEW': 'count-valued `@ctx` paths and parser noise (`~>`, folded-block `>`); see section 3',
}
for (const [k, v] of Object.entries(counts).sort((a, b) => b[1] - a[1]))
  console.log(`| ${k} | ${v} | ${REASON[k] || ''} |`)

// Guards that already existed at the integration head, i.e. NOT added by this pass.
const PRE_EXISTING = new Set([
  'jigs/Forms/customer-visit-form/clinical-report.jigx:369',
  'jigs/Forms/customer-visit-form/clinical-report.jigx:386',
  'jigs/Forms/customer-visit-form/grower-prospect.jigx:2890',
])
console.log(`
## 3. Sites carrying the \`$type(x) = 'number'\` guard

\`added\` = changed by this pass. \`pre-existing\` = already guarded at the integration
head (the \`missingCount\` mirror and the purchase-frequency errorText).

| file:line | origin | expression |
|---|---|---|`)
for (const r of cls.filter(r => r.verdict === 'LEAVE-already-type-guarded')) {
  const key = rel(r.file) + ':' + r.line
  const origin = PRE_EXISTING.has(key) ? 'pre-existing' : '**added**'
  console.log(`| ${key} | ${origin} | \`${r.text.replace(/\|/g, '\\|').slice(0, 100)}\` |`)
}
